-- =============================================================================
-- 陷阱汇总（与 eval/cases.yaml 的 note 字段对应）
-- -----------------------------------------------------------------------------
--  ① dim_region.region_group 存「华东区」，用户说「华东」           → 等值匹配 0 行
--  ② dim_product 两级类目，选错列不报错但答案错                     → 静默错误
--  ③ dim_product.cost_price，算毛利必须跨表 join                    → 跨表口径
--  ④ dim_customer.birth_date 存生日不存年龄，且可 NULL              → 需换算 + NULL 处理
--  ⑤ 注册地 vs 收货地两个 region_id，约 15% 订单跨区                → 口径二义
--  ⑥ orders.order_status 含 cancelled，不排除则销售额虚高约 12%      → 分母污染
--  ⑦ 三个金额字段互不相等（差额来自积分与运费）                     → 口径二义
--  ⑧ order_time 带时分秒，等值比较命中 0 行                         → 边界错误
--  ⑨ 「销量」= 订单数 / 件数 / 金额 三种口径                        → 口径三义
--  ⑩ SUM(item_amount) ≠ SUM(pay_amount) ≠ SUM(total_amount)        → 口径三义
--  ⑪ 退货率：分母三种 × 状态三种，且订单月 ≠ 退款月                 → 口径多维
--  ⑫ refunds.item_id 可空，内连接静默丢 40% 整单退                  → 静默丢数
--
-- 一句话总结这份 Schema 的作用：
--   它把「Text-to-SQL 的准确率」从「模型能力问题」转化成了「工程口径问题」，
--   从而让「语义层 + 护栏 + 评测集」成为必需品，而不是炫技。
-- =============================================================================
